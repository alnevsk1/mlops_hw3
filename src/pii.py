"""Чистка персональных данных.

В медицинских тестах НМО персональных данных почти нет, и счётчики будут
близки к нулю. Стадия всё равно обязательна: ноль, полученный проверкой, —
это результат, а ноль, полученный отсутствием проверки, — это надежда.

Осторожно с датами. Голый шаблон dd.mm.yyyy в этом источнике выбивает
«Приказ Минздрава России от 23.11.2021 N 925н» — то есть ровно тот текст,
которым варианты ответа отличаются друг от друга. Поэтому дата маскируется
только рядом с маркером рождения: цена ошибки первого рода здесь выше.
"""

import re

# Телефон: +7 / 8, затем 10 цифр с любыми разделителями.
PHONE = re.compile(r"(?:\+7|\b8)[\s\-(]{0,3}\d{3}[\s\-)]{0,3}\d{3}[\s\-]?\d{2}[\s\-]?\d{2}\b")
EMAIL = re.compile(r"\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}\b")
BIRTH_DATE = re.compile(
    r"(?P<pre>(?:дат[аеы]\s+рождения|год\s+рождения|родил(?:ся|ась)|"
    r"\bг\.\s?р\.|\bд\.\s?р\.)\s*[:\-—]?\s*)"
    r"(?:0?[1-9]|[12]\d|3[01])[.\-/](?:0?[1-9]|1[0-2])[.\-/](?:19|20)\d{2}\b",
    re.IGNORECASE,
)

PATTERNS: dict[str, re.Pattern[str]] = {
    "phone": PHONE,
    "email": EMAIL,
    "birth_date": BIRTH_DATE,
}
# Шаблон замены, а не просто строка: у даты надо сохранить маркер
# («дата рождения»), иначе вместе с ПДн из примера уходит смысл.
PLACEHOLDERS: dict[str, str] = {
    "phone": "[PHONE]",
    "email": "[EMAIL]",
    "birth_date": r"\g<pre>[DATE]",
}


def scrub(text: str) -> tuple[str, dict[str, int]]:
    """Заменить найденные ПДн плейсхолдерами. Возвращает текст и счётчик по типам."""
    hits: dict[str, int] = {}
    for name, pattern in PATTERNS.items():
        text, count = pattern.subn(PLACEHOLDERS[name], text)
        if count:
            hits[name] = count
    return text, hits
